const Quran = {
  surahs: SURAHS,
  surah(n) { return SURAHS[n - 1]; },

  // ترتيب الآية في المصحف كله (1..6236)
  index(s, a) {
    let i = 0;
    for (let k = 0; k < s - 1; k++) i += SURAHS[k].ayahs;
    return i + a;
  },

  // نقاط مرجعية معروفة الصفحة: بداية كل سورة وبداية كل جزء (الجزء n يبدأ بالصفحة 20n-18)
  _anchors: null,
  anchors() {
    if (this._anchors) return this._anchors;
    const m = new Map();
    SURAHS.forEach((s) => m.set(this.index(s.n, 1), s.page));
    JUZ_STARTS.forEach(([s, a], k) => { if (k > 0) m.set(this.index(s, a), 20 * (k + 1) - 18); });
    m.set(6237, 605);
    this._anchors = [...m.entries()].sort((x, y) => x[0] - y[0]);
    return this._anchors;
  },

  // موضع تقريبي بالصفحات (عدد عشري) لبداية آية
  pagePos(s, a) {
    const idx = this.index(s, a);
    const an = this.anchors();
    for (let k = 0; k < an.length - 1; k++) {
      const [i0, p0] = an[k], [i1, p1] = an[k + 1];
      if (idx >= i0 && idx < i1) return p0 + ((idx - i0) / (i1 - i0)) * (p1 - p0);
    }
    return 605;
  },

  // عدد الأوجه (الصفحات) التقريبي لمقطع، مقرّب لأقرب نصف
  pages(fs, fa, ts, ta) {
    if (!fs || !ts) return 0;
    let start = this.pagePos(fs, fa);
    let endSurah = ts, endAyah = ta + 1;
    if (endAyah > SURAHS[ts - 1].ayahs) { endSurah = ts + 1; endAyah = 1; }
    let end = endSurah > 114 ? 605 : this.pagePos(endSurah, endAyah);
    if (end < start) [start, end] = [end, start];
    return Math.max(0.5, Math.round((end - start) * 2) / 2);
  },

  pageOf(s, a) { return Math.floor(this.pagePos(s, a)); },

  juzOf(s, a) {
    const idx = this.index(s, a);
    let j = 1;
    for (let k = 0; k < 30; k++) if (this.index(...JUZ_STARTS[k]) <= idx) j = k + 1;
    return j;
  },

  // آخر آية في الجزء
  juzEnd(j) {
    if (j === 30) return [114, 6];
    const [s, a] = JUZ_STARTS[j];
    return a > 1 ? [s, a - 1] : [s - 1, SURAHS[s - 2].ayahs];
  },

  juzStart(j) { return JUZ_STARTS[j - 1]; },

  // بعد آية معيّنة: الآية التالية
  next(s, a) {
    if (a < SURAHS[s - 1].ayahs) return [s, a + 1];
    return s < 114 ? [s + 1, 1] : [114, 6];
  },

  label(s, a) { return `${SURAHS[s - 1].name} ${a}`; },
  range(fs, fa, ts, ta) {
    if (fs === ts) return `${SURAHS[fs - 1].name} ${fa}–${ta}`;
    return `${SURAHS[fs - 1].name} ${fa} – ${SURAHS[ts - 1].name} ${ta}`;
  },
};

